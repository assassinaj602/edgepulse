#!/usr/bin/env python3
"""
EdgePulse Statistical Analysis and Visualization Script.

Analyzes all_traces.csv generated by run_experiment.dart, calculates
Mann-Whitney U tests for statistical significance, and outputs 3 publication-ready
figures in docs/assets/figures/.
"""

import os
import sys
import json
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from scipy import stats

def main():
    csv_path = os.path.join("results", "all_traces.csv")
    if not os.path.exists(csv_path):
        print(f"Error: {csv_path} not found. Run 'dart run run_experiment.dart' first.")
        sys.exit(1)

    print(f"Reading experiment traces from {csv_path}...")
    df = pd.read_csv(csv_path)

    figures_dir = os.path.join("..", "..", "docs", "assets", "figures")
    os.makedirs(figures_dir, exist_ok=True)

    # Column mapping tolerance
    duration_col = 'duration_ms' if 'duration_ms' in df.columns else 'total_duration_ms'
    peak_rss_col = 'memory_peak_mb' if 'memory_peak_mb' in df.columns else ('mem_after_rss_mb' if 'mem_after_rss_mb' in df.columns else 'memory_end_mb')

    df['total_duration_ms'] = pd.to_numeric(df[duration_col], errors='coerce')
    df['mem_after_rss_mb'] = pd.to_numeric(df[peak_rss_col], errors='coerce')

    # Load scenario metadata from individual JSON files if scenario column not in CSV
    if 'scenario' not in df.columns:
        scenarios_by_id = {}
        results_dir = "results"
        for fname in os.listdir(results_dir):
            if fname.endswith(".json"):
                fpath = os.path.join(results_dir, fname)
                try:
                    with open(fpath, 'r') as f:
                        data = json.load(f)
                        traces = data.get('traces', [])
                        for t in traces:
                            tid = t.get('trace_id')
                            scen = t.get('metadata', {}).get('scenario', 'baseline')
                            if tid:
                                scenarios_by_id[tid] = scen
                except Exception:
                    pass
        df['scenario'] = df['trace_id'].map(scenarios_by_id).fillna('baseline')

    models = df['model_id'].unique()
    scenarios = ['baseline', 'memory_pressure', 'thermal_throttle']

    print("\n========================================================")
    print(" 📊 STATISTICAL SUMMARY & MANN-WHITNEY U TESTS")
    print("========================================================\n")

    for model in models:
        print(f"--- Model: {model} ---")
        model_df = df[df['model_id'] == model]

        for scenario in scenarios:
            sub = model_df[model_df['scenario'] == scenario]
            if len(sub) == 0:
                continue
            dur = sub['total_duration_ms']
            rss = sub['mem_after_rss_mb']
            print(f"  [{scenario:<16}] N={len(sub):<2} | "
                  f"Duration: mean={dur.mean():.1f}ms, std={dur.std():.1f}ms, min={dur.min():.1f}ms, max={dur.max():.1f}ms | "
                  f"RSS Peak: {rss.max():.1f}MB")

        baseline_dur = model_df[model_df['scenario'] == 'baseline']['total_duration_ms']
        
        for scenario in ['memory_pressure', 'thermal_throttle']:
            target_dur = model_df[model_df['scenario'] == scenario]['total_duration_ms']
            if len(baseline_dur) > 0 and len(target_dur) > 0:
                stat, p_val = stats.mannwhitneyu(baseline_dur, target_dur, alternative='two-sided')
                n1, n2 = len(baseline_dur), len(target_dur)
                effect_size = 1 - (2 * stat / (n1 * n2))
                sig = "YES (p < 0.05)" if p_val < 0.05 else "NO (p >= 0.05)"
                print(f"  Mann-Whitney U (baseline vs {scenario}): U={stat:.1f}, p={p_val:.4e}, effect_size={effect_size:.3f} -> Statistically Significant: {sig}")
        print()

    # Figure 1: Memory Curves
    fig, axes = plt.subplots(1, len(models), figsize=(15, 4.5), sharey=True)
    if len(models) == 1:
        axes = [axes]

    colors = {'baseline': '#2b5c8f', 'memory_pressure': '#d95f02', 'thermal_throttle': '#7570b3'}

    for idx, model in enumerate(models):
        ax = axes[idx]
        model_df = df[df['model_id'] == model]
        for scenario in scenarios:
            sub = model_df[model_df['scenario'] == scenario].reset_index(drop=True)
            if len(sub) > 0:
                ax.plot(sub.index + 1, sub['mem_after_rss_mb'], label=scenario, color=colors.get(scenario, '#333333'), linewidth=1.8)
        ax.set_title(f"Model: {model}")
        ax.set_xlabel("Run Index")
        if idx == 0:
            ax.set_ylabel("Memory RSS (MB)")
        ax.grid(True, linestyle='--', alpha=0.5)
        ax.legend()

    plt.tight_layout()
    fig1_path = os.path.join(figures_dir, "memory_curves.png")
    plt.savefig(fig1_path, dpi=300)
    plt.close()
    print(f"Saved figure 1: {fig1_path}")

    # Figure 2: Latency Boxplot
    fig, ax = plt.subplots(figsize=(10, 5))
    plot_data = []
    plot_labels = []

    for model in models:
        for scenario in scenarios:
            sub = df[(df['model_id'] == model) & (df['scenario'] == scenario)]['total_duration_ms']
            if len(sub) > 0:
                plot_data.append(sub.values)
                plot_labels.append(f"{model}\n({scenario})")

    bp = ax.boxplot(plot_data, tick_labels=plot_labels, patch_artist=True)
    box_colors = ['#2b5c8f', '#d95f02', '#7570b3'] * len(models)
    for patch, color in zip(bp['boxes'], box_colors):
        patch.set_facecolor(color)
        patch.set_alpha(0.7)

    ax.set_title("Inference Latency Distribution Across Stress Scenarios")
    ax.set_ylabel("Duration (ms)")
    ax.grid(True, linestyle='--', alpha=0.5)
    plt.xticks(rotation=15)
    plt.tight_layout()
    fig2_path = os.path.join(figures_dir, "latency_boxplot.png")
    plt.savefig(fig2_path, dpi=300)
    plt.close()
    print(f"Saved figure 2: {fig2_path}")

    # Figure 3: Thermal Distribution
    fig, ax = plt.subplots(figsize=(8, 4.5))
    thermal_states = ['nominal', 'fair', 'serious', 'critical', 'unknown']
    t_colors = {'nominal': '#2ca02c', 'fair': '#ff7f0e', 'serious': '#d62728', 'critical': '#9467bd', 'unknown': '#7f7f7f'}

    thermal_counts = {scen: {ts: 0 for ts in thermal_states} for scen in scenarios}
    for scenario in scenarios:
        sub = df[df['scenario'] == scenario]
        if 'thermal_state' in sub.columns:
            counts = sub['thermal_state'].value_counts()
            for ts, cnt in counts.items():
                if ts in thermal_counts[scenario]:
                    thermal_counts[scenario][ts] = cnt

    bottoms = np.zeros(len(scenarios))
    for ts in thermal_states:
        vals = [thermal_counts[scen][ts] for scen in scenarios]
        if sum(vals) > 0:
            ax.bar(scenarios, vals, bottom=bottoms, label=ts, color=t_colors[ts])
            bottoms += np.array(vals)

    ax.set_title("Thermal State Distribution Across Scenarios")
    ax.set_ylabel("Trace Count")
    ax.set_xlabel("Scenario")
    ax.legend(title="Thermal State")
    ax.grid(True, linestyle='--', alpha=0.5, axis='y')
    plt.tight_layout()
    fig3_path = os.path.join(figures_dir, "thermal_distribution.png")
    plt.savefig(fig3_path, dpi=300)
    plt.close()
    print(f"Saved figure 3: {fig3_path}")

    print("\n✅ Python statistical analysis & figure generation complete!")

if __name__ == '__main__':
    main()
